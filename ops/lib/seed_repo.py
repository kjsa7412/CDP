# YAML 에서 스칼라의 첫 글자가 이것들이면 인용해야 한다.
YAML_SPECIAL_HEAD = ''.join(chr(c) for c in (91, 123, 38, 42, 33, 124, 62, 37, 64, 96, 39, 34, 63, 44))


def render_work(d):
    # YAML 에서 [ { & * 등으로 시작하는 스칼라는 인용해야 한다.
    # '[오기재] ...' 를 그대로 적으면 배열로 파싱돼 제목이 사라진다.
    title = d['title']
    if title[:1] in YAML_SPECIAL_HEAD or ': ' in title:
        title = "'" + title.replace("'", "''") + "'"
    fm = ['---', 'id: %s' % d['id'], 'title: %s' % title, 'date: %s' % d['date'],
          'author: %s' % d['author']]
    # 값이 있을 때만 적는다 (`확정` 은 work() 에서 이미 지웠다).
    # 쓸 수 있는 값이 하나도 없다 -- 있으면 `ctx check` 가 오류로 막는다.
    if d['status']:
        fm.append('status: %s' % d['status'])
    if d['touches']:
        fm.append('touches:')
        for c in d['touches']:
            fm.append('  - %s' % c)
    else:
        fm.append('touches: []')
    if d['supersedes']:
        fm.append('supersedes: %s' % d['supersedes'])
    if d['attachments']:
        fm.append('attachments:')
        for a in d['attachments']:
            fm.append('  - %s' % a)
    if d['tags']:
        fm.append('tags: [%s]' % ', '.join(d['tags']))
    fm.append('---')
    return '\n'.join(fm) + '\n\n# %s\n\n%s\n' % (d['title'], d['body'].strip())


