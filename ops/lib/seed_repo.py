def fill_applied(text):
    """작업 기록이 있는 섹션의 `applied: null` 을 채운다.

    **'미작성'은 상태가 아니다.** 지식공유문서를 남기면 관리 문서 파생은
    필수이므로, 작업 기록이 있는데 파생이 안 된 섹션은 상태가 아니라
    **오류**다 -- `ctx check` 가 커밋을 막는다.

    옛 시드는 그런 섹션 8곳을 일부러 비워 두고 "아직 정리되지 않았습니다"를
    적어 밀림·미작성을 시연했다. 그 개념이 없어졌으므로 시연도 없어진다 --
    시드는 **커밋 가능한 정상 레포**를 만든다(17단계).

    가장 **최신** 작업을 싣는다. 옛것을 실으면 그 뒤 후속이 남아 또 오류다.
    작업 기록이 아직 없는 섹션은 null 그대로 둔다 -- 실을 것이 없는 것은
    위반이 아니다.
    """
    latest = {}
    for d in WORK:
        for c in d['touches']:
            v = c.split(':', 1)[1] if ':' in c else c
            if v not in latest or d['date'] > latest[v][0]:
                latest[v] = (d['date'], d['id'])

    out, cur, filled = [], None, False
    for ln in text.split(chr(10)):
        if ln.startswith('## '):
            cur = re.split(r'\s+(?:—|--)\s+', ln[3:].strip())[0].strip()
            filled = False
        if ln.strip() == '<!-- applied: null -->' and cur in latest:
            out.append('<!-- applied: %s -->' % latest[cur][1])
            filled = True
            continue
        # 채운 섹션에 남은 미작성 안내는 걷는다
        if filled and ln.lstrip().startswith(u'> ⚠ 아직 정리되지 않았습니다'):
            continue
        out.append(ln)
    return chr(10).join(out)



