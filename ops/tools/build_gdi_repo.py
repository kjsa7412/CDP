def scan_screens():
    """문서에 실제로 나온 화면ID만 모은다."""
    seen = {}
    for root, _dirs, fns in os.walk(SRC_WORK):
        for fn in fns:
            if not fn.lower().endswith(('.md', '.txt')):
                continue
            p = os.path.join(root, fn)
            raw = io.open(p, 'rb').read()
            t = None
            for enc in ('utf-8-sig', 'cp949', 'utf-8'):
                try:
                    t = raw.decode(enc)
                    break
                except Exception:
                    pass
            if t is None:
                continue
            for sid in SCREEN_RE.findall(t):
                seen[sid] = seen.get(sid, 0) + 1
    return seen


