def render(d):
    fm = ['---', 'id: %s' % d['id'], 'title: %s' % d['title'], 'date: %s' % d['date'],
          'author: %s' % d['author'], 'status: %s' % d['status'], 'touches:']
    for c in d['touches']:
        fm.append('  - %s' % c)
    if d['supersedes']:
        fm.append('supersedes: %s' % d['supersedes'])
    if d['attachments']:
        fm.append('attachments:')
        for a in d['attachments']:
            fm.append('  - %s' % a)
    if d['tags']:
        fm.append('tags: [%s]' % ', '.join(d['tags']))
    fm.append('---')

    body = ['', '# %s' % d['title'], '', '## 무엇이 바뀌었나', '', d['what'].strip(), '']
    if d['omit_why']:
        body += ['## 왜', '']  # 제목만 있고 내용이 없다
    else:
        body += ['## 왜', '', d['why'].strip(), '']
    body += ['## 누구에게 영향', '', d['who'].strip(), '']
    body += ['## 후속 조치', '', d['next'].strip(), '']
    return '\n'.join(fm) + '\n'.join(body)


