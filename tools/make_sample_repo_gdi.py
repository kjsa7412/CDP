    for t in finals:
        out.append('- `%s` — %s' % (t['table_nm'], t['table_logical_nm']))
    out.append('')

    for t in finals:
        cl = sorted(by_table.get(t['table_id'], []), key=lambda x: int(x['col_seq'] or 0))
        out += ['---', '', '## %s' % t['table_nm'], '',
                '**%s**' % t['table_logical_nm'], '']
        if t.get('description') and t['description'] != t['table_logical_nm']:
            out += ['> %s' % t['description'], '']
        if not cl:
            out += ['컬럼 정의가 덤프에 없다.', '']
            continue
        out += ['| # | 논리명 | 물리명 | 타입 | 길이 | NULL | 키 | 기본값 |',
                '|---|---|---|---|---|:--:|:--:|---|']
        for c in cl:
            out.append('| %s | %s | `%s` | %s | %s | %s | %s | %s |' % (
                c['col_seq'], c['logical_col_nm'] or '', c['physical_col_nm'] or '',
                c['data_type'] or '', c['data_length'] or '',
                'Y' if str(c['is_nullable']).lower() in ('true', 'y', '1') else 'N',
                'PK' if str(c['is_key']).lower() in ('true', 'y', '1') else '',
                c['default_val'] or ''))
        out.append('')
        keys = [c for c in cl if str(c['is_key']).lower() in ('true', 'y', '1')]
        if keys:
            out += ['**키** — %s' % ', '.join('`%s`' % k['physical_col_nm'] for k in keys), '']
    return '\n'.join(out)


