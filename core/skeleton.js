// 새 지식 레포의 빈 틀 — v1.0 개편안 §8.2 · I9. **레포에는 지식만 둔다.**
//
// 패키지를 붓던 자리(`newRepo` 의 복사 · 훅 · 도구 층)를 이 틀 하나가 대신한다. 서식은 서식집(`forms/`)에 있고
// 큐레이터가 문서를 세울 때 서버가 찍는다(`managed.add { form }`). 스킬 · CLAUDE 블록은 서버 번들의 kit 이 작업 레포에
// 낸다. 그래서 여기에는 지식이 담길 자리만 있다 — README · 어휘 · 등록부 · `docs/` · `work/` · git 설정 둘.
//
// 순수하다 — 파일 이름 → 글을 낸다. 쓰는 것은 `newRepo` 다.

const NL = '\n'

export function skeletonFiles({ name, title = null, rebuiltFrom = null, date = null } = {}) {
  const lead = title || (rebuiltFrom ? `${rebuiltFrom} 의 작업 기록을 옮겨 다시 세운 지식 레포${date ? `(${date})` : ''}` : '지식 레포')
  return {
    'README.md': [
      `# ${name}`,
      '',
      lead,
      '',
      'CDP 지식 레포다. **작업 기록(`work/`)이 원천**이고, 관리 문서(`docs/`)는 큐레이터가 기록을 보고 반영한다.',
      '쓰는 길은 서버의 `save` 하나다 — 서버 화면이나 작업 레포의 Claude Code(MCP)로 쓴다. 이 폴더를 손으로 고치지 않는다.',
      '',
      '| 자리 | 무엇 |',
      '|---|---|',
      '| `work/` | 작업 기록 — 한 작업에 한 파일. 사건이라 고치지 않는다 · 첨부는 `work/assets/<id>/` |',
      '| `docs/` | 관리 문서 — 대상마다 지금의 정본 섹션. 큐레이터가 서식집에서 세우고 반영한다 |',
      '| `_vocab.md` | 좌표 어휘 — 정본 이름과 별칭 |',
      '| `_managed.md` | 등록부 — 좌표가 어느 관리 문서의 어느 섹션에 대응하나 |',
      '',
    ].join(NL),

    '_vocab.md': [
      '# 좌표 어휘',
      '',
      '이 파일이 통제 어휘(authority file)다. 같은 대상을 가리키는 여러 표기 중',
      '**정본을 하나 정하고 나머지를 `aliases` 로 연결한다.** `aliases` 가 이 파일의',
      '진짜 핵심이다 — 정본 목록만 있으면 작성자만 편해지고, `aliases` 가 있어야',
      '수신자가 자연어로 물어도 걸린다.',
      '',
      '**운영 원칙** — 추가는 한 줄, 삭제는 하지 않는다(`deprecated` 로 표시),',
      'alias 는 발견될 때마다 추가한다.',
      '',
      '---',
      '',
      '## 아직 비어 있다',
      '',
      '첫 좌표는 작업 기록을 남길 때(save 의 `vocab`) · 큐레이터가 첫 관리 문서를 세울 때 여기 더해진다.',
      '',
      '| 자리 | 모양 |',
      '|---|---|',
      '| 타입 절 | `## <타입>` — **공백 없는 머리글이 타입이다.** 설명 절의 머리글에는 공백을 넣는다 |',
      '| 좌표 줄 | 타입 절 아래 한 줄에 하나 — 목록 표시 · 백틱 안의 `타입:값` · ` — ` · 설명 |',
      '| 별칭 | 좌표 줄 바로 아래 들여 쓴 `aliases:` 한 줄 — 쉼표로 가른다 |',
      '| 정착도에서 빼기 | 타입 절 바로 아래 `excluded:` 한 줄 — 작업을 묶는 축(업무 영역 · 도메인)일 때 |',
      '',
      '**타입 절의 순서가 화면 · CLI 의 카테고리 순서다.** 자주 쓰는 것을 위에 둔다.',
      '',
    ].join(NL),

    '_managed.md': [
      '# 관리 문서 등록부',
      '',
      '좌표가 어느 관리 문서의 어느 섹션에 대응하는지 **여기에만** 적는다.',
      '매핑이 두 곳에 있으면 반드시 어긋난다.',
      '',
      '| 좌표 패턴 | 관리 문서 | 섹션 |',
      '|---|---|---|',
      '',
      '**행은 큐레이터가 더한다** — 새 관리 문서를 서식집에서 세울 때 save 의 `managed: [{ pattern, doc, form }]` 가',
      '행과 깨끗한 빈 문서를 같이 만든다.',
      '',
      '**패턴은 위에서부터 먼저 걸리는 것을 쓴다.** 그리고 **대소문자를 구분한다** —',
      '`시험:ut-…` 는 `시험:UT-*` 에 걸리지 않는다.',
      '',
      '## 등록부에 없는 좌표는 정상이다',
      '',
      '관리 문서는 **자주 쓰는 내용을 하나로 모아 둔 것**이다. 모든 것이 여기 녹지',
      '않는다 — 덜 쓰는 것을 하나로 모으는 부담이 이득보다 크다. 덜 쓰는 내용의',
      '원천은 **그 작업 기록 자체**다.',
      '',
    ].join(NL),

    // 줄바꿈을 LF 로 — 서버(Linux)와 PC(Windows)가 같은 바이트를 본다. 첨부(그림 · pdf)는 그대로
    '.gitattributes': ['* text=auto eol=lf', '', '*.png binary', '*.jpg binary', '*.jpeg binary', '*.gif binary', '*.webp binary', '*.pdf binary', ''].join(NL),

    // 제출물은 형상관리하지 않는다 — 정본은 md 다. 엑셀 · 한글 · 발표 자료는 필요할 때 md 에서 만든다
    '.gitignore': ['/submit/', '*.xlsx', '*.hwp', '*.hwpx', '*.pptx', ''].join(NL),

    'docs/.gitkeep': '',
    'work/.gitkeep': '',
  }
}
